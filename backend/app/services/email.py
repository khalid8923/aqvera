"""Email service for AQVERA.

Supports SMTP-based email delivery for password reset and email verification
tokens. When SMTP is not configured, the service reports "not_configured" and
does not attempt to send email. Tokens are generated by the auth service but
are never returned via API responses when email delivery is unavailable,
preventing token leakage.

This module is intentionally provider-agnostic: it uses Python's built-in
smtplib and does not depend on any third-party email SaaS.
"""

from __future__ import annotations

import smtplib
import ssl
from email.message import EmailMessage
from typing import Optional

from app.core.config import settings


class EmailService:
    """Transactional email delivery via SMTP.

    When SMTP settings are incomplete, `is_configured()` returns False and
    `send()` raises `EmailNotConfiguredError`. Callers should catch this and
    degrade gracefully.
    """

    class EmailNotConfiguredError(Exception):
        """Raised when SMTP is not configured and send() is called."""

    def is_configured(self) -> bool:
        """Return True if SMTP is fully configured."""
        return settings.email_configured

    def config_state(self) -> dict:
        """Return a safe, serializable description of email configuration state.

        Never exposes secret values (SMTP_PASS).
        """
        return {
            "configured": self.is_configured(),
            "host": settings.SMTP_HOST,
            "port": settings.SMTP_PORT,
            "user": settings.SMTP_USER,
            "from": settings.SMTP_FROM,
            "use_tls": settings.SMTP_USE_TLS,
        }

    def send(
        self,
        to: str,
        subject: str,
        body_text: str,
        body_html: Optional[str] = None,
    ) -> None:
        """Send an email. Raises EmailNotConfiguredError if SMTP is not set up."""
        if not self.is_configured():
            raise self.EmailNotConfiguredError(
                "SMTP is not configured. Set SMTP_HOST, SMTP_PORT, SMTP_USER, "
                "SMTP_PASS, and SMTP_FROM to enable email delivery."
            )

        msg = EmailMessage()
        msg["From"] = settings.SMTP_FROM
        msg["To"] = to
        msg["Subject"] = subject
        msg.set_content(body_text)
        if body_html:
            msg.add_alternative(body_html, subtype="html")

        context = ssl.create_default_context() if settings.SMTP_USE_TLS else None
        with smtplib.SMTP(settings.SMTP_HOST, settings.SMTP_PORT) as server:
            if settings.SMTP_USE_TLS:
                server.starttls(context=context)
            if settings.SMTP_USER and settings.SMTP_PASS:
                server.login(settings.SMTP_USER, settings.SMTP_PASS)
            server.send_message(msg)


email_service = EmailService()
